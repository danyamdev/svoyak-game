export const DEMO_ROUNDS: DemoCategory[][] = categoryNames.map((round, roundIndex) =>
  round.map((title, categoryIndex) => ({
    id: `round-${roundIndex + 1}-category-${categoryIndex + 1}`,
    title,
    questions: ROUND_PRICE_SCALES[roundIndex].map((price, questionIndex) => {
      const source = sampleQuestions[categoryIndex][questionIndex]

      return {
        id: `round-${roundIndex + 1}-category-${categoryIndex + 1}-question-${questionIndex + 1}`,
        category: title,
        price,
        prompt:
          roundIndex === 0
            ? source[0]
            : `${source[0]} (демонстрационный вопрос раунда ${roundIndex + 1})`,
        answer: source[1],
      }
    }),
  })),
)

export function findDemoQuestion(questionId: string): DemoQuestion | undefined {
  return DEMO_ROUNDS.flatMap((round) => round.flatMap(({ questions }) => questions)).find(
    ({ id }) => id === questionId,
  )
}
